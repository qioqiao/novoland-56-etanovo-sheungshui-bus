import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";

// iOS-inspired local corner, not Apple's proprietary device outline.
// References: https://www.figma.com/blog/desperately-seeking-squircles/
// https://help.figma.com/hc/en-us/articles/360050986854
// Start with the iOS 60% smoothing footprint (1.6 R). Solve the inner
// control handle for exact G2 joins to the circle, instead of Figma's
// approximate a = 2b shortcut. The first three controls are collinear,
// giving zero curvature where each corner meets a perfectly straight edge.
const extent = 100;
const smoothing = 0.6;
const radius = extent / (1 + smoothing);
const angle = (Math.PI / 4) * smoothing;
const d = radius * (1 - Math.cos(angle));
const c = d / Math.tan(angle);
const b = (3 * Math.hypot(c, d) ** 3) / (2 * d * radius);
const endX = extent - radius + radius * Math.sin(angle);
const a = endX - b - c;
const entry = [[0, 0], [a, 0], [a + b, 0], [endX, d]];
const mirror = ([x, y]) => [extent - y, extent - x];
const exit = entry.toReversed().map(mirror);

function curvature(points, atEnd) {
  const p = atEnd ? points.toReversed() : points;
  const v = p[1].map((n, i) => 3 * (n - p[0][i]));
  const w = p[2].map((n, i) => 6 * (n - 2 * p[1][i] + p[0][i]));
  return Math.abs(v[0] * w[1] - v[1] * w[0]) / Math.hypot(...v) ** 3;
}
assert.ok(a > 0 && b > 0 && c > 0 && d > 0);
assert.equal(curvature(entry, false), 0);
assert.equal(curvature(exit, true), 0);
assert.ok(Math.abs(curvature(entry, true) - 1 / radius) < 1e-12);
assert.ok(Math.abs(curvature(exit, false) - 1 / radius) < 1e-12);
for (const curve of [entry, exit]) {
  for (let i = 1; i < curve.length; i++) {
    assert.ok(curve[i][0] >= curve[i - 1][0]);
    assert.ok(curve[i][1] >= curve[i - 1][1]);
  }
}

const n = (value) => Number(value.toFixed(8));
const xy = (point) => point.map(n).join(" ");
// Extend only the two interior edges, so independently rasterized mask
// layers overlap instead of exposing subpixel seams. The contour is unchanged.
const bleed = 4;
const tileExtent = extent + bleed;
const path = `M-${bleed} 0 L0 0 C${entry.slice(1).map(xy).join(" ")} A${n(radius)} ${n(radius)} 0 0 1 ${xy(exit[0])} C${exit.slice(1).map(xy).join(" ")} L100 ${tileExtent} L-${bleed} ${tileExtent} Z`;
const transforms = [
  ["tl", "translate(100 0) scale(-1 1)", "left top"],
  ["tr", `translate(${bleed} 0)`, "right top"],
  ["br", `translate(${bleed} ${tileExtent}) scale(1 -1)`, "right bottom"],
  ["bl", `translate(100 ${tileExtent}) scale(-1 -1)`, "left bottom"],
];
const image = (transform) => {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${tileExtent} ${tileExtent}"><path fill="black" transform="${transform}" d="${path}"/></svg>`;
  return `url("data:image/svg+xml,${encodeURIComponent(svg)}")`;
};
// The square logo uses one complete contour, so it has no tiled seams.
// Keep the same curvature construction and a finite straight section per side.
const logoSize = 32;
const logoRadius = 9;
const logoExtent = logoRadius * (1 + smoothing);
const logoScale = logoExtent / extent;
const local = point => point.map(value => value * logoScale);
const corners = [
  ([x, y]) => [logoSize - logoExtent + x, y],
  ([x, y]) => [logoSize - y, logoSize - logoExtent + x],
  ([x, y]) => [logoExtent - x, logoSize - y],
  ([x, y]) => [y, logoExtent - x],
];
const segment = transform => `L${xy(transform([0, 0]))} C${entry.slice(1).map(point => xy(transform(local(point)))).join(' ')} A${logoRadius} ${logoRadius} 0 0 1 ${xy(transform(local(exit[0])))} C${exit.slice(1).map(point => xy(transform(local(point)))).join(' ')}`;
const logoPath = `M${logoExtent} 0 ${corners.map(segment).join(' ')} Z`;
const logoMask = `url("data:image/svg+xml,${encodeURIComponent(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><path d="${logoPath}" fill="black"/></svg>`)}")`;
assert.ok(logoSize - 2 * logoExtent > 0);
const begin = "/* BEGIN GENERATED ISLAND CORNERS */";
const end = "/* END GENERATED ISLAND CORNERS */";
const css = `${begin}
/* Generated by scripts/write-island-corners.mjs.
 * Four square corner tiles keep their physical size. Two opaque strips
 * fill the centre with exact horizontal/vertical edges: the whole card
 * is NEVER stretched from a squircle. CSS resizing also follows the
 * existing card-height animation without a ResizeObserver or JS frame.
 * An interior-only 4% bleed prevents fractional-pixel stitching seams.
 * Both prefixed and standard masks use the same geometry on iOS/WebKit.
 */
@supports (mask-image: linear-gradient(#000, #000)) or (-webkit-mask-image: linear-gradient(#000, #000)) {
  .brand-icon {
    border-radius: 0;
    -webkit-mask: ${logoMask} center / 100% 100% no-repeat;
    mask: ${logoMask} center / 100% 100% no-repeat;
  }
  .island-shell {
    filter: drop-shadow(0 12px 14px #12192221);
  }
  .island {
    --island-corner-size: calc(var(--island-radius) * 1.6);
    --island-corner-tile-size: calc(var(--island-corner-size) * 1.04);
${transforms.map(([name, transform]) => `    --island-corner-${name}: ${image(transform)};`).join("\n")}
    --island-mask:
${transforms.map(([name, , position]) => `      var(--island-corner-${name}) ${position} / var(--island-corner-tile-size) var(--island-corner-tile-size) no-repeat,`).join("\n")}
      linear-gradient(#000, #000) center / calc(100% - var(--island-corner-size) * 2) 100% no-repeat,
      linear-gradient(#000, #000) center / 100% calc(100% - var(--island-corner-size) * 2) no-repeat;
    border-color: transparent;
    border-radius: 0;
    box-shadow: none;
    -webkit-mask: var(--island-mask);
    mask: var(--island-mask);
  }
}
${end}`;
const file = new URL("../styles.css", import.meta.url);
const original = await readFile(file, "utf8");
const start = original.indexOf(begin);
const finish = original.indexOf(end);
assert.equal(start < 0, finish < 0, "Incomplete generated corner block");
const updated = start < 0
  ? `${original.trimEnd()}\n\n${css}\n`
  : original.slice(0, start) + css + original.slice(finish + end.length);
await writeFile(file, updated);
await writeFile(new URL('../favicon.svg', import.meta.url), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><path d="${logoPath}" fill="#141719"/><path d="M9 23 23 9M10 9h13v13" fill="none" stroke="#c5f27a" stroke-width="3.5" stroke-linecap="round" stroke-linejoin="round"/></svg>\n`);

// Check actual supported layout extremes: resizing must leave four finite
// straight sections, and the same square geometry at every corner.
for (const [width, height, r] of [[280, 258, 27], [343, 258, 27], [400, 310, 27], [686, 290, 32], [686, 480, 32]]) {
  const cornerSize = r * 1.6;
  assert.ok(width - 2 * cornerSize > 0 && height - 2 * cornerSize > 0);
}
console.log("Generated four identical local corner masks; zero edge curvature, G2 arc joins, monotone convex handles, and straight edge budgets verified.");
